"""Generate payload.wxs: the PyInstaller folder tree as WiX directories.

WiX's ``Files`` element places a glob's matches in one directory, which
flattens ``_internal`` and breaks the app. This walks the real tree and emits
one Directory + ComponentGroup per folder.

Usage:  python tools/make_payload.py
"""

from __future__ import annotations

from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
PAYLOAD = ROOT / "dist" / "Ledger" / "_internal"
OUTPUT = ROOT / "payload.wxs"


def main() -> int:
    if not PAYLOAD.is_dir():
        raise SystemExit(f"Payload not found: {PAYLOAD}. Build with PyInstaller first.")

    directories: list[dict[str, str]] = []
    counter = [0]

    def walk(folder: Path, parent_id: str | None, path_parts: list[str]) -> None:
        for child in sorted(folder.iterdir()):
            if not child.is_dir():
                continue
            counter[0] += 1
            directory_id = f"d{counter[0]}"
            directories.append(
                {
                    "id": directory_id,
                    "name": child.name,
                    "parent": parent_id or "",
                    "rel": "\\".join([*path_parts, child.name]),
                }
            )
            walk(child, directory_id, [*path_parts, child.name])

    # the _internal folder itself
    counter[0] += 1
    root_id = f"d{counter[0]}"
    directories.append(
        {"id": root_id, "name": "_internal", "parent": "", "rel": "_internal"}
    )
    walk(PAYLOAD, root_id, ["_internal"])

    # which folders actually contain files
    with_files = {
        entry["id"]: entry
        for entry in directories
        if any(p.is_file() for p in (ROOT / "dist" / "Ledger" / entry["rel"]).iterdir())
    }

    lines: list[str] = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by tools/make_payload.py - do not edit by hand. -->",
        '<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">',
        "",
        "  <Fragment>",
        '    <DirectoryRef Id="INSTALLFOLDER">',
    ]

    def emit_tree(parent: str | None, indent: int) -> None:
        for entry in directories:
            if (entry["parent"] or None) != parent:
                continue
            pad = "  " * indent
            lines.append(f'{pad}<Directory Id="{entry["id"]}" Name="{escape(entry["name"])}">')
            emit_tree(entry["id"], indent + 1)
            lines.append(f"{pad}</Directory>")

    emit_tree(None, 3)
    lines.extend(["    </DirectoryRef>", "  </Fragment>", "", "  <Fragment>"])
    lines.append('    <FeatureGroup Id="Payload">')
    for directory_id in with_files:
        lines.append(f'      <ComponentGroupRef Id="g_{directory_id}" />')
    lines.extend(["    </FeatureGroup>", "  </Fragment>", ""])

    for directory_id, entry in with_files.items():
        lines.append("  <Fragment>")
        lines.append(
            f'    <ComponentGroup Id="g_{directory_id}" Directory="{directory_id}">'
        )
        lines.append(
            f'      <Files Include="dist\\Ledger\\{entry["rel"]}\\*" />'
        )
        lines.append("    </ComponentGroup>")
        lines.append("  </Fragment>")
        lines.append("")

    lines.append("</Wix>")

    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(
        f"directories={len(directories)} with_files={len(with_files)} "
        f"-> {OUTPUT.name}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
